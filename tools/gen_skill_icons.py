# Colours that get no outline in one icon (thin lines like a fishing line or sparkles).
NO_OUTLINE = {"fishing": "k", "spellcasting": "Gfgab", "nightwalker": "W", "charger": "Aa",
              "cooking": "O", "running": "Aa", "smithing": "f", "maces": ""}


def palette(category_rgb):
    p = dict(BASE)
    p["A"] = mix(category_rgb, (255, 255, 255), 0.35)
    p["a"] = category_rgb
    p["b"] = mix(category_rgb, (0, 0, 0), 0.30)
    p["c"] = mix(category_rgb, (0, 0, 0), 0.55)
    p["o"] = mix(category_rgb, (16, 14, 14), 0.78)
    return p


def render(name, text, category_rgb):
    rows = text.strip("\n").split("\n")
    if len(rows) != 16 or any(len(r) != 16 for r in rows):
        raise SystemExit(f"{name}: map must be 16x16, got {[len(r) for r in rows]}")
    pal = palette(category_rgb)
    img = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    bare = NO_OUTLINE.get(name, "")
    filled = [[ch != "." and ch not in bare for ch in row] for row in rows]
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            if ch not in pal:
                raise SystemExit(f"{name}: unknown colour '{ch}' at {x},{y}")
            img.putpixel((x, y), pal[ch] + (255,))
    outline = pal["o"] + (255,)
    for y in range(16):
        for x in range(16):
            if rows[y][x] != ".":
                continue
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < 16 and 0 <= ny < 16 and filled[ny][nx]:
                    img.putpixel((x, y), outline)
                    break
    return img


def main():
    order, skills, colours = read_categories()
    missing = [s for s in order if s not in ICONS]
    extra = [s for s in ICONS if s not in skills]
    if missing or extra:
        raise SystemExit(f"missing icons {missing}, maps for unknown skills {extra}")
    os.makedirs(OUT, exist_ok=True)
    images = {}
    for sid in order:
        img = render(sid, ICONS[sid], colours[skills[sid]])
        img.save(os.path.join(OUT, sid + ".png"))
        images[sid] = img
    print(f"wrote {len(images)} icons to {OUT}")
    if "--sheet" in sys.argv:
        sheet(order, skills, images, sys.argv[sys.argv.index("--sheet") + 1])


def sheet(order, skills, images, path):
    """8x per icon plus 1x and 2x copies, on a mid grey and a dark tile, labelled."""
    cols = 6
    cw, ch = 220, 170
    rows = (len(order) + cols - 1) // cols
    out = Image.new("RGB", (cols * cw, rows * ch), (40, 42, 46))
    d = ImageDraw.Draw(out)
    for n, sid in enumerate(order):
        cx, cy = (n % cols) * cw, (n // cols) * ch
        d.rectangle([cx + 4, cy + 4, cx + 4 + 136, cy + 4 + 136], fill=(139, 139, 139))
        out.paste(images[sid].resize((128, 128), Image.NEAREST), (cx + 8, cy + 8), images[sid].resize((128, 128), Image.NEAREST))
        d.rectangle([cx + 146, cy + 8, cx + 146 + 40, cy + 8 + 60], fill=(24, 24, 28))
        out.paste(images[sid], (cx + 150, cy + 12), images[sid])
        big = images[sid].resize((32, 32), Image.NEAREST)
        out.paste(big, (cx + 150, cy + 32), big)
        d.text((cx + 8, cy + 146), f"{sid} ({skills[sid].lower()})", fill=(230, 230, 230))
    out.save(path)
    print("sheet", path)


if __name__ == "__main__":
    main()
