"""16x16 skill icons in vanilla item style, one per skill.

Each icon is a hand-written pixel map below. The script adds the 1 px outline itself (any empty
pixel that touches a filled one on a side), so a map holds only the fill and any inner lines ('o').
Category colours come from SkillPalette.java and the skill list from Skill.java, so a new skill or a
changed colour shows up here on the next run.

    python3 tools/gen_skill_icons.py            # writes the PNGs
    python3 tools/gen_skill_icons.py --sheet out.png   # also a labelled 8x contact sheet

Rules for a new map: 16 rows of 16 characters, light from the top left, 3 to 4 shades per
material, no anti-aliasing. Letters 'A' 'a' 'b' 'c' are the skill's category colour (lightest to
darkest), so categories read as families.
"""
