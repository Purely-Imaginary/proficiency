def hexrgb(v):
    return ((v >> 16) & 0xFF, (v >> 8) & 0xFF, v & 0xFF)


def mix(a, b, t):
    return tuple(round(a[i] * (1 - t) + b[i] * t) for i in range(3))


def read_categories():
    """skill id -> category name, and category name -> rgb, read from the Java sources."""
    skills = {}
    order = []
    with open(os.path.join(JAVA, "skill/Skill.java"), encoding="utf-8") as f:
        for m in re.finditer(r'^\s+[A-Z_]+\("([a-z_]+)", SkillCategory\.([A-Z_]+)', f.read(), re.M):
            skills[m.group(1)] = m.group(2)
            order.append(m.group(1))
    colours = {}
    with open(os.path.join(JAVA, "client/SkillPalette.java"), encoding="utf-8") as f:
        for m in re.finditer(r"case ([A-Z_]+) -> 0x[0-9A-Fa-f]{2}([0-9A-Fa-f]{6});", f.read()):
            colours[m.group(1)] = hexrgb(int(m.group(2), 16))
    return order, skills, colours


